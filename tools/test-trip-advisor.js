'use strict';
const assert=require('assert'),fs=require('fs');
const data=JSON.parse(fs.readFileSync('_data/travel/shandong_2026.yml'));
const config=JSON.parse(fs.readFileSync('_data/travel/shandong_advisor.yml'));
const advisor=require('../assets/js/trip-advisor'),routes=require('../assets/js/trip-routes');
const state={selections:JSON.parse(JSON.stringify(data.defaults)),routeOrders:{},daySettings:{},meals:{},hotelBudgets:{},hotelChecks:{},completedStops:{}};
const by=Object.fromEntries(data.pois.map(p=>[p.id,p]));
const original=JSON.stringify(state);
Object.keys(config.presets).forEach(day=>['light','standard','rich'].forEach(level=>{
  const p=advisor.packagePlan(data,state,day,level,config,routes);
  assert.ok(p.ids.length>=2);p.ids.forEach(id=>assert.ok(by[id]));
  assert.equal(JSON.stringify(state),original,'预览不得更改原方案');
  Object.keys(state.selections).filter(k=>!k.startsWith('attraction')).forEach(k=>assert.deepEqual(p.state.selections[k],state.selections[k]));
  const attractions=p.ids.filter(id=>by[id].type==='attraction');
  assert.ok(!(attractions.includes('a-polar')&&attractions.includes('a-underwater')));
  assert.ok(advisor.estimate(data,p.ids,p.state.daySettings[day],config).total>0);
}));
assert.equal(advisor.packagePlan(data,state,'d2','rich',config,routes),null);
const hotel=advisor.hotelImpact(data,state,'hotel-yantai','h-yantai-b',routes,config);
assert.deepEqual(hotel.rows.map(r=>r.day),['d5','d6','d7']);
assert.ok(hotel.rows.every(r=>!r.ids.includes('h-yantai-a')));
assert.deepEqual(hotel.state.selections['hotel-weihai'],state.selections['hotel-weihai']);
assert.equal(JSON.stringify(state),original);
const insert=advisor.insertion(data,routes.route(data,state,'d6'),'r-yantai-alt');
assert.ok(insert.existing||Number.isFinite(insert.km));
assert.deepEqual(advisor.insertion(data,['h-yantai-a','h-yantai-a'],'h-yantai-a'),{existing:true});
assert.equal(advisor.insertion(data,[],'r-yantai-alt'),null);
const anchored=JSON.parse(JSON.stringify(state));anchored.meals.d6={lunch:{primary:'f-yantai',after:'h-yantai-a'}};
assert.equal(advisor.hotelImpact(data,anchored,'hotel-yantai','h-yantai-b',routes,config).state.meals.d6.lunch.after,'h-yantai-b');
data.pois.forEach(p=>{const html=advisor.lastMile(p,config);assert.ok(html.includes('待确认'));assert.ok(html.includes('高德查停车场'));});
assert.ok(advisor.lastMile(by['a-underwater'],config).includes('该地址不是已核验的停车场入口'));
const simulation=require('../assets/js/trip-simulation');
const stops=[by['h-yantai-a'],by['f-yantai'],by['h-yantai-a']];
assert.equal(simulation.simulate(stops,{napMinutes:120},null).end-simulation.simulate(stops,{},null).end,120);
const meal=simulation.simulate(stops,{mealTimes:{'f-yantai':1020}},null);
assert.ok(meal.rows[1].arrival>=1020);assert.equal(meal.rows[1].late,0);
console.log('advisor OK: 21 packages, preview isolation, hotel cross-day impact, last-mile uncertainty, nap budget');
