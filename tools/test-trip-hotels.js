'use strict';
const assert = require('assert');
const fs = require('fs');
const data = JSON.parse(fs.readFileSync('_data/travel/shandong_2026.yml','utf8'));
const { stays } = require('../assets/js/trip-hotels');
const state = {selections:JSON.parse(JSON.stringify(data.defaults)),hotelBudgets:{}};
let actual = stays(data,state);
assert.deepStrictEqual(actual.map(s=>s.nights),[2,3,3]);
assert.deepStrictEqual(actual.map(s=>[s.checkin,s.checkout]),[['2026-09-27','2026-09-29'],['2026-09-29','2026-10-02'],['2026-10-02','2026-10-05']]);
assert.ok(actual.every(s=>s.total===null));
state.hotelBudgets[actual[0].id]={nightly:600,rooms:2};
assert.equal(stays(data,state)[0].total,2400);
state.selections['hotel-yantai']=['h-yantai-b'];
actual=stays(data,state);
assert.equal(actual[0].id,'h-yantai-b');
assert.equal(actual[0].total,null);
assert.equal(actual[0].nights,2);
state.hotelBudgets['h-yantai-b']={nightly:0,rooms:1};
assert.equal(stays(data,state)[0].total,0);
console.log('hotel stay tests OK: dates, nights, missing quotes and hotel changes');
