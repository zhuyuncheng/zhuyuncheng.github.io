'use strict';
const assert=require('assert'),fs=require('fs');
const data=JSON.parse(fs.readFileSync('_data/travel/shandong_2026.yml','utf8'));
const routes=require('../assets/js/trip-routes'),execution=require('../assets/js/trip-execution'),hotels=require('../assets/js/trip-hotels');
const state={selections:JSON.parse(JSON.stringify(data.defaults)),routeOrders:{},meals:{},expenses:{},bookings:{},hotelBudgets:{}};
const diners=data.pois.filter(p=>p.type==='restaurant' && p.city==='烟台');
assert.ok(diners.length>=2);
state.meals.d6={lunch:{primary:diners[0].id,backup:diners[1].id,after:'a-yantaishan'},dinner:{primary:diners[0].id,after:'a-yantaishan'}};
let ids=routes.route(data,state,'d6');
assert.equal(ids.filter(id=>id===diners[0].id).length,2);assert.ok(!ids.includes(diners[1].id));
let first=ids.indexOf(diners[0].id),second=ids.lastIndexOf(diners[0].id),done={[routes.stopKey(ids,first)]:'done'};
assert.equal(routes.status(done,ids,first),'done');assert.equal(routes.status(done,ids,second),null);
done[routes.stopKey(ids,first)]='';assert.equal(routes.status(done,ids,first),'');
state.meals.d6.lunch.primary=diners[1].id;assert.ok(routes.route(data,state,'d6').includes(diners[1].id));
state.meals.d6={lunch:{},dinner:{}};assert.ok(!routes.route(data,state,'d6').some(id=>diners.some(p=>p.id===id)));
state.hotelBudgets['h-yantai-a']={nightly:500,rooms:1};state.expenses.d5={food:100,tickets:0};
const sum=execution.budget(data,state,hotels.stays(data,state));assert.equal(sum.total,1100);assert.equal(sum.missing,84);
const map=Object.fromEntries(data.days.map(d=>[d.id,routes.route(data,state,d.id)]));
state.bookings.d5={'a-penglai':{time:'2026-09-27T10:30',cancel:'2026-09-26T18:00'}};
let ics=execution.calendar(data,state,map),unfolded=ics.replace(/\r\n /g,'');
assert.ok(unfolded.includes('DTSTART:20260927T023000Z'));assert.ok(unfolded.includes('DTSTART:20260926T100000Z'));
assert.equal((unfolded.match(/BEGIN:VEVENT/g)||[]).length,16);ics.split('\r\n').forEach(line=>assert.ok(Buffer.byteLength(line)<=75));
const html=execution.offlineHTML(data,map,{});assert.ok(html.includes('午睡'));assert.ok(!/<script|<link|<img[^>]+src="https?:/.test(html));assert.ok(html.includes('联网后高德定位'));
assert.equal(routes.route(data,state,'d10').filter(id=>id==='h-qingdao-a').length,2);
console.log('execution tests OK: meals, independent visits, missing costs, calendar timezone, offline document');
